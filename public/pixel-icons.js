  // --- Building the SVG ---

  /**
   * Returns the SVG path data (the d attribute) for an icon's rows. The whole icon is one path:
   * each horizontal run of filled pixels becomes a rectangle one pixel tall.
   */
  function pathData(rows) {
    let d = '';
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length;) {
        if (row[x] !== '#') {
          x++;
          continue;
        }
        let end = x;
        while (row[end] === '#') end++;
        d += `M${x} ${y}h${end - x}v1h${x - end}z`;
        x = end;
      }
    });
    return d;
  }

  /**
   * Returns a new <svg> element for the named icon, or null when there is no such icon. Its
   * viewBox is the icon's grid, its edges stay crisp, and it is hidden from screen readers and from
   * the keyboard: the button or label around it says what it is.
   */
  function svg(name) {
    const rows = ICONS[name];
    if (!rows) return null;
    const ns = 'http://www.w3.org/2000/svg',
      element = document.createElementNS(ns, 'svg'),
      path = document.createElementNS(ns, 'path');
    element.setAttribute('viewBox', `0 0 ${rows[0].length} ${rows.length}`);
    element.setAttribute('aria-hidden', 'true');
    element.setAttribute('focusable', 'false');
    element.setAttribute('shape-rendering', 'crispEdges');
    path.setAttribute('d', pathData(rows));
    path.setAttribute('fill', 'currentColor');
    element.append(path);
    return element;
  }

  /**
   * Replaces the content of every [data-icon] element in scope (the whole page by default) with
   * the icon it names. An element that names no known icon is left as it is.
   */
  function render(scope = document) {
    for (const node of scope.querySelectorAll('[data-icon]')) {
      const icon = svg(node.dataset.icon);
      if (icon) node.replaceChildren(icon);
    }
  }

  return { ICONS, pathData, svg, render };
